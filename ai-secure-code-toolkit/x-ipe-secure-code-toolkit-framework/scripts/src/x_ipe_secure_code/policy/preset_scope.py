"""`preset resolve` and `preset scope-save` (FEATURE-001-F): a Preset as 001-C scope input and the
single Preset-based scope-save orchestration (DAO-006 (1)).

The delivered 001-C functions are called unchanged: the proposal digest is the unchanged digest over
the mode and the considered references (the generated `preset:<slug>@sha256:<digest>` clue is
information-only text, not part of it), and a Preset-based scope is an ordinary `clues` record.
"""

from __future__ import annotations

import dataclasses
import re
from datetime import UTC, datetime
from typing import Any

from ..atomic import LockHeld
from ..knowledge import catalog, durable, exit_journal, store
from ..knowledge.catalog import PRESET, CatalogError
from ..projects import knowledge_root
from ..results import Result
from . import resolve, scope, service
from .refs import is_utf8

CLUE_NOTE = (
    "information-only clue text generated by the toolkit from the Preset file it read; it is not part "
    "of the proposal digest and is not re-checked when the scope is saved"
)
COMPARE_STEP = "Compare the applicability summary with the current task before asking for confirmation"
DEFAULT_MESSAGE = "The default Preset is proposed because no clues were given"
DEFAULT_STEP = (
    "Repair the default Preset or choose another scope; Apply All only if the user explicitly chooses it "
    "(secure-code policy resolve --all)"
)
NO_DEFAULT_STEP = "No default Preset: propose Apply All with secure-code policy resolve --all"
CLUE_STEP = "Copy the clue exactly from preset resolve (preset:<name>@sha256:<digest>) and use mode 'clues'"
CLUE = re.compile(r"preset:([a-z0-9-]{1,64})@sha256:[0-9a-f]{64}")
ADOPTION = (
    "nothing adopted yet — the user must confirm, then: "
    "secure-code preset scope-save {} --decisions FILE --confirmed"
)


def _proposal(
    session: exit_journal.Session, name: str, languages: list[str], *, default: bool
) -> dict[str, Any]:
    entry = catalog.read_one(session.tree, PRESET, name)
    lib = resolve.snapshot(session.tree)
    data = resolve.build(lib, entry.rels, False, languages)
    data["adoption"] = ADOPTION.format(name)
    doc = entry.data
    data["preset"] = {
        "name": name,
        "default": name == "default",
        "snapshot_at": doc["snapshot_at"],
        "snapshot_note": catalog.SNAPSHOT_NOTE,
        "applicability_summary": doc["applicability_summary"],
        "query_intent": doc["query_intent"],
        "query_intent_note": catalog.QUERY_NOTE,
        "file_digest": entry.digest,
        "clue": f"preset:{name}@{entry.digest}",
        "clue_note": CLUE_NOTE,
    }
    data["notices"].append(
        {
            "code": "PRESET_PROPOSED",
            "message": f"Preset {name} proposed from its stored references; "
            "nothing is adopted until the user confirms",
        }
    )
    if default:
        data["notices"].append(
            {"code": "DEFAULT_PRESET_PROPOSED", "highlight": True, "message": DEFAULT_MESSAGE}
        )
    return data


def _steps(data: dict[str, Any], name: str, default: bool) -> list[str]:
    save = (
        "Ask the user to confirm the scope, then run: "
        f"secure-code preset scope-save {name} --decisions FILE --confirmed"
    )
    steps = [
        save if s.startswith("Ask the user to confirm the scope") else s for s in resolve.next_steps(data)
    ]
    if data["status"] == resolve.MAINTENANCE_NEEDED:
        return [*steps, DEFAULT_STEP] if default else steps
    return [COMPARE_STEP, *steps]


def _finish(
    command: str,
    data: dict[str, Any],
    recovered: dict[str, Any] | None,
    name: str,
    default: bool,
    output: str | None,
) -> Result:
    if recovered:
        data["recovered_exit"] = recovered
    return service._finish(command, data, _steps(data, name, default), output)


def resolve_preset(project: str | None, name: str, languages: list[str], output: str | None = None) -> Result:
    """Resolve a Preset's stored references through the 001-C proposal contract; read-only.

    Args:
        project: Explicit project root.
        name: Preset identity (slug).
        languages: Artifact languages for advisory notes (never filters).
        output: Optional file receiving the full result.

    Returns:
        The 001-C proposal data plus `preset` (identity, snapshot, summary, generated clue).
    """
    command = "preset resolve"
    if not is_utf8(languages):
        return Result.refused(
            command,
            "REQUEST_INVALID",
            "--language must be valid UTF-8 text",
            "Pass language names such as java or python",
        )
    root = knowledge_root(project, command)
    if isinstance(root, Result):
        return root
    taken = catalog.in_session(
        command, root, lambda s: _proposal(s, name, languages, default=False), write=True
    )
    if isinstance(taken, Result):
        return taken
    data, recovered = taken
    return _finish(command, data, recovered, name, False, output)


def resolve_default(project: str | None, languages: list[str], output: str | None = None) -> Result:
    """No clues: propose the reserved `default` Preset if present (never builds Apply All itself)."""
    command = "preset resolve"
    if not is_utf8(languages):
        return Result.refused(
            command,
            "REQUEST_INVALID",
            "--language must be valid UTF-8 text",
            "Pass language names such as java or python",
        )
    root = knowledge_root(project, command)
    if isinstance(root, Result):
        return root

    def run(session: exit_journal.Session) -> dict[str, Any] | None:
        dfd = session.tree.opt_dir(catalog.PRESETS_REL)
        try:
            found = durable.entry(dfd, "default.json") if dfd is not None else None
        finally:
            durable.close(dfd)
        return None if found is None else _proposal(session, "default", languages, default=True)

    taken = catalog.in_session(command, root, run, write=True)
    if isinstance(taken, Result):
        if taken.problems and taken.problems[0].code in ("PATH_UNSAFE", "PRESET_INVALID"):
            taken.next_steps = [DEFAULT_STEP]
        return taken
    data, recovered = taken
    if data is None:
        absent = {
            "status": "no_default_preset",
            "adopted": [],
            "adoption": "nothing proposed — no default Preset",
        }
        return exit_journal.with_recovered(Result(command, True, absent, [], [NO_DEFAULT_STEP]), recovered)
    return _finish(command, data, recovered, "default", True, output)


def save(project: str | None, name: str, decisions_path: str, confirmed: bool) -> Result:
    """Save the confirmed Preset-based scope through the unchanged 001-C confirmation path.

    Under the knowledge lock the Preset is read again and its current references are the considered
    references; the confirmed proposal digest is kept, so any change of references or rule state
    since the proposal is refused as STALE_CONFIRMATION by the unchanged `scope.check_decisions`.
    """
    command = "preset scope-save"
    if not confirmed:
        return Result.refused(
            command,
            "CONFIRMATION_REQUIRED",
            "The scope was not marked as confirmed",
            "Save only after the user confirmed the scope, then pass --confirmed",
        )
    root = knowledge_root(project, command)
    if isinstance(root, Result):
        return root
    try:
        decisions = scope.load_decisions(decisions_path)
    except scope.ScopeError as exc:
        return Result.refused(command, exc.code, exc.message, exc.next_step)
    match = CLUE.fullmatch(decisions.clues)
    if decisions.mode != "clues" or match is None or match.group(1) != name:
        return Result.refused(
            command,
            "DECISIONS_INVALID",
            f"A scope saved from Preset {name!r} needs mode 'clues' and its generated clue",
            CLUE_STEP,
        )
    recovered: dict[str, Any] | None = None
    try:
        with exit_journal.session(root, write=True) as session:
            recovered = session.recovered
            current = catalog.read_one(session.tree, PRESET, name).rels
            confirmed_now = dataclasses.replace(decisions, considered=current)
            lib = resolve.snapshot(session.tree)
            data = resolve.build(lib, current, False, decisions.language_context)
            store._pause_point("preset_scope_save_locked")
            adopted, not_adopted, outside = scope.check_decisions(confirmed_now, data, lib, session.tree)
            record = scope.build_record(
                confirmed_now, adopted, not_adopted, datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")
            )
            rel, created, stored = scope.publish(root, record, session.tree)
    except CatalogError as exc:
        return exit_journal.with_recovered(exc.result(command), recovered)
    except scope.ScopeError as exc:
        return exit_journal.with_recovered(
            Result.refused(command, exc.code, exc.message, exc.next_step), recovered
        )
    except LockHeld as exc:
        return exit_journal.with_recovered(
            Result.refused(command, "LOCKED", str(exc), service.RETRY), recovered
        )
    except store.StoreError as exc:
        step = exc.next_step or "Replace the symbolic link with a real folder"
        return exit_journal.with_recovered(Result.refused(command, exc.code, exc.message, step), recovered)
    except OSError as exc:
        return exit_journal.with_recovered(
            Result.refused(command, "IO_ERROR", f"Scope record could not be written: {exc}"), recovered
        )
    out = {
        "scope_id": stored["scope_id"],
        "path": rel,
        "created": created,
        "mode": stored["mode"],
        "adopted_rules": [a["rule"] for a in stored["adopted"]],
        "not_adopted": stored["not_adopted"],
        "created_at": stored["created_at"],
    }
    if outside:
        out["outside_confirmed_scope"] = outside
    out["preset"] = {"name": name, "clue": decisions.clues, "clue_note": CLUE_NOTE}
    return exit_journal.with_recovered(
        Result(
            command,
            True,
            out,
            [],
            ["Give this scope_id to Guard or Copilot; they load it with: secure-code scope show --scope ID"],
        ),
        recovered,
    )
